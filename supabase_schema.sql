-- 1. TABELA DE LOUVORES (SONGS)
CREATE TABLE IF NOT EXISTS public.songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    artist TEXT,
    tags TEXT,
    slides_json TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar RLS (Row Level Security) e permitir leitura/escrita
ALTER TABLE public.songs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura de louvores" ON public.songs;
CREATE POLICY "Permitir leitura de louvores" ON public.songs FOR SELECT USING (true);

DROP POLICY IF EXISTS "Permitir inserção de louvores" ON public.songs;
CREATE POLICY "Permitir inserção de louvores" ON public.songs FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir atualização de louvores" ON public.songs;
CREATE POLICY "Permitir atualização de louvores" ON public.songs FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Permitir exclusão de louvores" ON public.songs;
CREATE POLICY "Permitir exclusão de louvores" ON public.songs FOR DELETE USING (true);

-- 2. TABELA DE AJUSTES E CONFIGURAÇÕES (SETTINGS)
CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura de configurações" ON public.settings;
CREATE POLICY "Permitir leitura de configurações" ON public.settings FOR SELECT USING (true);

DROP POLICY IF EXISTS "Permitir escrita de configurações" ON public.settings;
CREATE POLICY "Permitir escrita de configurações" ON public.settings FOR ALL USING (true);

-- 3. TABELA DE ROTEIROS DO CULTO (SETLISTS)
CREATE TABLE IF NOT EXISTS public.setlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    items_json TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.setlists ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura de roteiros" ON public.setlists;
CREATE POLICY "Permitir leitura de roteiros" ON public.setlists FOR SELECT USING (true);

DROP POLICY IF EXISTS "Permitir escrita de roteiros" ON public.setlists;
CREATE POLICY "Permitir escrita de roteiros" ON public.setlists FOR ALL USING (true);

